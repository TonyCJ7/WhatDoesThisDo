"""Draws docs/assets/logo.png as terminal quadrant-block art, in 256 colours and true colour, and writes it into the three setup scripts.

Run after changing the logo (needs Pillow and numpy):  python3 setup/make-logo.py
"""
import re
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
SMALL = {"thin": 15, "squeeze": 8}  # stroke pixels eroded and pixels each letter moves inward, on the source image
VARIANTS = {34: None, 28: SMALL}
LETTERS = {  # hue range in degrees, and the direction the letter moves toward the centre
    "W": ((320, 360), (1, 1)),
    "D": ((15, 45), (-1, 1)),
    "T": ((60, 110), (1, -1)),
    "D2": ((195, 230), (-1, -1)),
    "?": ((255, 300), (-1, -1)),
}
START = "# logo-data:start (generated by setup/make-logo.py from docs/assets/logo.png, do not edit)"
END = "# logo-data:end"


def xterm256(r, g, b):
    def level(v):
        return 0 if v < 48 else 1 if v < 115 else (v - 35) // 40

    return 16 + 36 * level(r) + 6 * level(g) + level(b)


GLYPH = {0b0000: " ", 0b1000: "▘", 0b0100: "▝", 0b1100: "▀", 0b0010: "▖", 0b1010: "▌", 0b0110: "▞", 0b1110: "▛",
         0b0001: "▗", 0b1001: "▚", 0b0101: "▐", 0b1101: "▜", 0b0011: "▄", 0b1011: "▙", 0b0111: "▟", 0b1111: "█"}
MODES = ("256", "truecolor")


def mean(colors):
    return tuple(sum(c[i] for c in colors) // len(colors) for i in range(3))


def error(colors, m):
    return sum((c[i] - m[i]) ** 2 for c in colors for i in range(3))


def fg(color, mode):
    return f"38;5;{xterm256(*color)}" if mode == "256" else f"38;2;{color[0]};{color[1]};{color[2]}"


def bg(color, mode):
    return f"48;5;{xterm256(*color)}" if mode == "256" else f"48;2;{color[0]};{color[1]};{color[2]}"


def best_split(cells):
    best = None

    for mask in range(1, 16):
        front = [cells[i] for i in range(4) if mask >> (3 - i) & 1]
        back = [cells[i] for i in range(4) if not mask >> (3 - i) & 1]
        front_mean = mean(front)
        back_mean = mean(back) if back else None
        cost = error(front, front_mean) + (error(back, back_mean) if back else 0)

        if best is None or cost < best[0]:
            best = (cost, mask, front_mean, back_mean)

    return best[1:]


def letter_masks(image):
    """Every opaque pixel gets the letter whose hue it carries; outlines and highlights join the nearest letter."""
    hsv = np.array(image.convert("HSV"), dtype=int)
    hue, sat, val = hsv[..., 0] * 360 // 255, hsv[..., 1], hsv[..., 2]
    coloured = (np.array(image.getchannel("A")) > 128) & (sat > 90) & (val > 60)
    masks = {name: coloured & (hue >= lo) & (hue <= hi) for name, ((lo, hi), _) in LETTERS.items()}

    for name, mask in masks.items():
        if not mask.any():
            raise SystemExit(f"no pixels with the hue of {name}; update LETTERS for the new logo")

    rest = (np.array(image.getchannel("A")) > 128) & ~np.logical_or.reduce(list(masks.values()))

    reach = dict(masks)

    while rest.any():
        for name in masks:
            reach[name] = np.array(Image.fromarray(reach[name].astype(np.uint8) * 255).filter(ImageFilter.MaxFilter(5))) > 0
            taken = reach[name] & rest
            masks[name] |= taken
            rest &= ~taken

    return masks


def thin_and_squeeze(image, thin, squeeze):
    out = Image.new("RGBA", image.size, (0, 0, 0, 0))
    pixels = np.array(image)

    for name, mask in letter_masks(image).items():
        part = pixels.copy()
        part[~mask] = 0
        letter = Image.fromarray(part)
        letter.putalpha(letter.getchannel("A").filter(ImageFilter.MinFilter(thin)))
        dx, dy = LETTERS[name][1]
        moved = Image.new("RGBA", image.size, (0, 0, 0, 0))
        moved.paste(letter, (dx * squeeze, dy * squeeze))
        out.alpha_composite(moved)

    return out.crop(out.getchannel("A").getbbox())


def logo_pixels(width):
    image = Image.open(ROOT / "docs/assets/logo.png").convert("RGBA")
    image = image.crop(image.getchannel("A").getbbox())

    if VARIANTS[width]:
        image = thin_and_squeeze(image, **VARIANTS[width])

    return image.resize((width * 2, width), Image.LANCZOS)


def rows_for(width, mode, esc):
    """Each character cell holds a 2 by 2 block of pixels, drawn with the quadrant characters and two colours."""
    image = logo_pixels(width)
    pixels = image.load()
    rows = []

    for y in range(0, width, 2):
        row = "  "
        current = None

        for x in range(0, width * 2, 2):
            cells = [pixels[x, y], pixels[x + 1, y], pixels[x, y + 1], pixels[x + 1, y + 1]]
            opaque = [c[3] > 128 for c in cells]

            if not any(opaque):
                style, glyph = None, " "
            elif not all(opaque):
                mask = sum(bit << (3 - i) for i, bit in enumerate(opaque))
                style = f"{fg(mean([c[:3] for c, on in zip(cells, opaque) if on]), mode)};49"
                glyph = GLYPH[mask]
            else:
                mask, front, back = best_split([c[:3] for c in cells])
                style = f"{fg(front, mode)};{bg(back, mode) if back else '49'}"
                glyph = GLYPH[mask]

            if style != current:
                row += f"{esc}[{style}m" if style else f"{esc}[0m"
                current = style

            row += glyph

        rows.append(row.rstrip() + f"{esc}[0m")

    return rows


def shell_block():
    lines = [START]

    for width in VARIANTS:
        for mode in MODES:
            suffix = "TC" if mode == "truecolor" else "256"
            lines.append(f"LOGO_{width}_{suffix}='" + "\\n".join(rows_for(width, mode, "\\033")) + "'")

    lines.append(END)
    return "\n".join(lines)


def powershell_block():
    lines = [START]

    for width in VARIANTS:
        for mode in MODES:
            suffix = "TC" if mode == "truecolor" else "256"
            lines.append(f"$Logo{width}{suffix} = @'")
            lines.extend(rows_for(width, mode, "<ESC>"))
            lines.append("'@")

    lines.append(END)
    return "\n".join(lines)


def inject(path, block, encoding):
    text = path.read_text(encoding=encoding)
    pattern = re.compile(re.escape(START) + ".*?" + re.escape(END), re.S)

    if not pattern.search(text):
        raise SystemExit(f"{path}: markers not found")

    path.write_text(pattern.sub(lambda _: block, text), encoding=encoding)
    print(f"{path.relative_to(ROOT)}: logo data written")


if __name__ == "__main__":
    for name in ("setup-macos.sh", "setup-linux.sh"):
        inject(ROOT / "setup" / name, shell_block(), "utf-8")

    inject(ROOT / "setup" / "setup-windows.ps1", powershell_block(), "utf-8-sig")
