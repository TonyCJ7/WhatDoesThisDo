"""Draws docs/assets/logo.png as terminal half-block art and writes it into the three setup scripts.

Run after changing the logo:  python3 setup/make-logo.py
"""
import re
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
WIDTHS = (44, 32)
START = "# logo-data:start (generated by setup/make-logo.py from docs/assets/logo.png, do not edit)"
END = "# logo-data:end"


def xterm256(r, g, b):
    def level(v):
        return 0 if v < 48 else 1 if v < 115 else (v - 35) // 40

    return 16 + 36 * level(r) + 6 * level(g) + level(b)


def rows_for(width, esc):
    image = Image.open(ROOT / "docs/assets/logo.png").convert("RGBA")
    image = image.crop(image.getchannel("A").getbbox()).resize((width, width), Image.LANCZOS)
    pixels = image.load()
    rows = []

    for y in range(0, width, 2):
        row = "  "
        current = None

        for x in range(width):
            top = pixels[x, y]
            bottom = pixels[x, y + 1] if y + 1 < width else (0, 0, 0, 0)
            top_on = top[3] > 128
            bottom_on = bottom[3] > 128

            if top_on and bottom_on:
                style = f"38;5;{xterm256(*top[:3])};48;5;{xterm256(*bottom[:3])}"
                glyph = "▀"
            elif top_on:
                style = f"38;5;{xterm256(*top[:3])};49"
                glyph = "▀"
            elif bottom_on:
                style = f"38;5;{xterm256(*bottom[:3])};49"
                glyph = "▄"
            else:
                style = None
                glyph = " "

            if style != current:
                row += f"{esc}[{style}m" if style else f"{esc}[0m"
                current = style

            row += glyph

        rows.append(row.rstrip() + f"{esc}[0m")

    return rows


def shell_block():
    lines = [START]

    for width in WIDTHS:
        lines.append(f"LOGO_{width}='" + "\\n".join(rows_for(width, "\\033")) + "'")

    lines.append(END)
    return "\n".join(lines)


def powershell_block():
    lines = [START]

    for width in WIDTHS:
        lines.append(f"$Logo{width} = @'")
        lines.extend(rows_for(width, "<ESC>"))
        lines.append("'@")

    lines.append(END)
    return "\n".join(lines)


def inject(path, block, encoding):
    text = path.read_text(encoding=encoding)
    pattern = re.compile(re.escape(START) + ".*?" + re.escape(END), re.S)

    if not pattern.search(text):
        raise SystemExit(f"{path}: markers not found")

    path.write_text(pattern.sub(lambda _: block, text), encoding=encoding)
    print(f"{path.relative_to(ROOT)}: logo data written")


for name in ("setup-macos.sh", "setup-linux.sh"):
    inject(ROOT / "setup" / name, shell_block(), "utf-8")

inject(ROOT / "setup" / "setup-windows.ps1", powershell_block(), "utf-8-sig")
